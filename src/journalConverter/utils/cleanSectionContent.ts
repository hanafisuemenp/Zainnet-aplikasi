/**
 * Utility to clean duplicate and unwanted section headings from generated academic text.
 * Complies with Pedoman Karya Tulis Ilmiah (PPKI 2020) BAB I & BAB III:
 * - Subheadings do NOT use alphabetical (A., B., C., D., E.) or numerical numbering.
 * - Subheading terms must not be duplicated or repeated in the first paragraph of content.
 */

export function cleanSectionContent(content: string, sectionTitle?: string): string {
  if (!content) return '';
  let text = String(content).trim();

  const titlesToClean = [
    sectionTitle,
    'PENDAHULUAN',
    'METODE PENELITIAN',
    'METODE',
    'HASIL PENELITIAN',
    'HASIL DAN PEMBAHASAN',
    'HASIL',
    'PEMBAHASAN',
    'KESIMPULAN DAN SARAN',
    'KESIMPULAN',
    'SARAN',
    'DAFTAR RUJUKAN',
    'DAFTAR PUSTAKA',
  ].filter(Boolean) as string[];

  // Repeat up to 3 passes to strip nested repetitions (e.g. "C. HASIL PENELITIAN C. HASIL PENELITIAN. ...")
  for (let pass = 0; pass < 3; pass++) {
    const original = text;

    // Strip markdown headings (###, ##, #)
    text = text.replace(/^#+\s*/, '');

    for (const t of titlesToClean) {
      const escaped = t.replace(/[-\/\\^$*+?.()|[\]{}]/g, '\\$&');
      // Matches:
      // Optional bold / italics (** or __)
      // Optional prefix like "A.", "B.", "C.", "D.", "E.", "1.", "I.", "Bab IV", etc.
      // Followed by the section title
      // Optional closing bold / italics
      // Followed by optional punctuation (: or . or -) and trailing whitespace
      const regex = new RegExp(
        `^(\\*\\*|__)?\\s*(?:(?:BAB\\s+[IVX0-9]+|[A-Za-z0-9]+)[.)]\\s+)?${escaped}\\s*(\\*\\*|__)?\\s*[:.\\-]?\\s*`,
        'i'
      );
      text = text.replace(regex, '').trim();
    }

    if (text === original) break;
  }

  return text.trim();
}

/**
 * Normalizes bibliography entries according to PPKI 2020 BAB IV, hlm. 71-72:
 * - 1 author: Nama akhir dibalik, nama depan. Judul. Kota: Penerbit, Tahun.
 * - 2 authors: Nama pertama dibalik, nama kedua ditulis urutan lurus (contoh: Guntur, Romli dan A. Fawaid.)
 * - 3 or more authors: HANYA nama pertama yang ditulis (dibalik), lalu diikuti "dkk." atau "et al." (contoh: Alulu, Fadhlan, dkk.)
 */
export function normalizePpkIBibliographyEntry(entry: string): string {
  if (!entry) return '';
  let clean = entry.trim();

  // If already contains dkk. or et al., keep it clean
  if (/\b(dkk\.|et\s+al\.)/i.test(clean)) {
    return clean;
  }

  // Detect 3 or more authors before a period or book title
  // Pattern: "Author1, Author2, dan Author3." or "Author1, Author2, Author3, dan Author4."
  const threeAuthorsRegex = /^([^,]+,\s*[^,]+),\s*([^,]+),\s*(?:dan|and|&)\s*([^.]+)\./i;
  const matchThree = clean.match(threeAuthorsRegex);
  if (matchThree) {
    const firstAuthor = matchThree[1].trim();
    const rest = clean.substring(matchThree[0].length).trim();
    return `${firstAuthor}, dkk. ${rest}`;
  }

  return clean;
}

/**
 * Normalizes footnotes array ensuring every footnote item has a strictly unique ID,
 * sequential 1-based number, and valid text/sectionId properties.
 * Prevents React key collisions and formatting issues.
 */
export function normalizeFootnotes(rawFootnotes: any[]): any[] {
  if (!Array.isArray(rawFootnotes)) return [];
  const seenIds = new Set<string>();

  return rawFootnotes
    .filter((fn) => fn && typeof fn === 'object')
    .map((fn, idx) => {
      let uniqueId =
        fn.id && typeof fn.id === 'string' && fn.id.trim()
          ? fn.id.trim()
          : `fn_${idx + 1}`;

      // Deduplicate key if duplicate ID was generated by AI or multi-stage consolidation
      if (seenIds.has(uniqueId)) {
        uniqueId = `fn_${idx + 1}_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 6)}`;
      }
      seenIds.add(uniqueId);

      return {
        ...fn,
        id: uniqueId,
        number: idx + 1,
        text: typeof fn.text === 'string' ? fn.text : '',
        sectionId: fn.sectionId || 'pendahuluan',
      };
    });
}
